  function parseHash() {
    const o = {};
    location.hash.replace(/^#/, '').split('&').forEach(kv => { const [k, v] = kv.split('='); if (k) o[k] = decodeURIComponent(v || ''); });
    return { p: o.p ? clamp(parseInt(o.p, 10) || 1, 1, S.N || 999) : null, v: ['book', 'scroll', 'grid'].includes(o.v) ? o.v : null, q: o.q || null };
  }

  // ------------------------------------------------------------------ boot
  async function boot() {
    let cfg, man;
    try {
      [cfg, man] = await Promise.all([fetch('book/book.json').then(r => r.json()), fetch('book/manifest.json').then(r => r.json())]);
    } catch (e) {
      el.stage.innerHTML = '<p style="padding:40px;text-align:center;color:var(--ink-2)">The catalogue could not be loaded. Please reload the page.</p>';
      return;
    }
    S.cfg = cfg; S.man = man; S.N = man.pageCount; [S.PW, S.PH] = man.pageSize;
    el.bookHost.prepend(el.bookShadow);
    man.hotspots.forEach(h => { if (!S.hsByPage.has(h.page)) S.hsByPage.set(h.page, []); S.hsByPage.get(h.page).push(h); });
    if (S.sound === null) S.sound = cfg.settings.flipSound !== false;
    computeChapters();
    const hide = new Set(cfg.settings.hideInBookMode || []);
    Book.pages = range(1, S.N).filter(n => !hide.has(n));
    el.pageTotal.textContent = S.N;
    el.about.innerHTML = `${esc(cfg.brand)} ${esc(cfg.title)} · ${esc(cfg.publisher)}<br>${esc(cfg.address)}<br>Orders: <a href="mailto:${esc(cfg.contact.email)}">${esc(cfg.contact.email)}</a> · <a href="${esc(cfg.contact.website)}" target="_blank" rel="noopener">HST Medical website</a>`;
    el.optSound.checked = !!S.sound;
    el.optBlanks.checked = !!S.showBlanks;
    applyTheme(S.theme);
    setAuto(0);
    renderToc();
    renderRail();
    renderSaved();
    bind();

    const h = parseHash();
    const start = h.p || cfg.settings.startPage || 1;
    S.page = start;
    S.visible = [start];
    const view = h.v || store.get('view', 'book');

    // image tier is chosen once from the real stage: on-screen page width x device pixel ratio
    const sr = el.stage.getBoundingClientRect();
    const pageCss = Math.min(sr.width / 2, Math.max(200, sr.height - 56) * S.PW / S.PH);
    Images.hi = pageCss * (window.devicePixelRatio || 1) > 1250;
    // no lazy loading: every book page is requested now, nearest to the opening page first
    const si = Book.indexOf(start);
    Images.preloadAll(Book.pages.slice().sort((a, b) => Math.abs(Book.indexOf(a) - si) - Math.abs(Book.indexOf(b) - si)));
    const first = view === 'book' ? Book.spreadOf(start, false) : [start];
    const ready = Promise.all(first.map(n => Images.decode(Images.urlFor(n))));
    await Promise.race([ready, new Promise(r => setTimeout(r, 6000))]);

    setView(view, { page: start });
    requestAnimationFrame(() => requestAnimationFrame(() => el.loader.classList.add('gone')));
    setTimeout(() => { el.loader.hidden = true; }, 700);
    if (h.q) { openPanel('search'); applyQuery(h.q); }
    else setTimeout(() => ensureText(), 1500);

    const last = store.get('lastPage', null);
    if (!h.p && last && last > 3 && last <= S.N) setTimeout(() => toast(`Continue where you left off — p. ${last}`, 'Continue', () => goTo(last), 8000), 900);
    if (!store.get('coachSeen', false)) {
      el.coach.hidden = false;
      if (isTouch) el.coach.querySelector('p').innerHTML = '<b>Swipe</b> to turn pages. <b>Tap a product name</b> for pack sizes and item codes, or anywhere else to zoom in.';
      setTimeout(() => { el.coach.hidden = true; store.set('coachSeen', true); }, 14000);
    }
  }
  window.NVL = window.HST = { S, Book, Scroll, Grid, Zoom, Sound, goTo, setView, applyQuery, openProduct }; // handy for QA from the console
  boot();
