      if (this.mode === 'spread') {
        const idx = Book.indexOf(this.pages[0]);
        const sp = Book.spreadIdx(idx, false);
        const j = dir > 0 ? sp[sp.length - 1] + 1 : sp[0] - 1;
        if (j < 0 || j >= Book.pages.length) return null;
        return Book.spreadIdx(j, false).map(i => Book.pages[i]);
      }
      const list = S.view === 'scroll' ? Scroll.pages() : Book.pages;
      const i = list.indexOf(this.pages[0]);
      const j = i + dir;
      return j >= 0 && j < list.length ? [list[j]] : null;
