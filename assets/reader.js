      const W = el.zoomViewport.clientWidth, H = el.zoomViewport.clientHeight;
      if (cx == null) { cx = W / 2; cy = H / 2; }
      const nz = clamp(z, 1, 6), k = nz / this.z;
      this.tx = cx - (cx - this.tx) * k;
      this.ty = cy - (cy - this.ty) * k;
      this.z = nz;
      this.clampPan();
      this.apply();
